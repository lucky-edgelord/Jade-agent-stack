def outputs(root: Path) -> dict[str, str]:
    """every generated file, path → text"""
    tps = docs.topics()
    pages = docs.all_pages()
    out: dict[str, str] = {}
    order = [t["topic"] for t in tps]
    search = []
    for i, t in enumerate(tps):
        p = pages[t["topic"]]
        src = f"{t['topic']}.md" if not p["meta"].get("generated") else "(generated from the code)"
        body = p["body"].strip()
        # markdown for agents: frontmatter, version pin, body, footer
        fm = {k: p["meta"][k] for k in ("title", "summary", "tags", "applies_to", "audience", "since") if k in p["meta"]}
        out[f"docs/md/{t['topic']}.md"] = "---\n" + "\n".join(f"{k}: {json.dumps(v)}" for k, v in fm.items()) + f"\nversion: {compat.TOOLKIT}\n---\n" + body + "\n\n" + FOOT_MD.format(src=src) + "\n"
        prev = f'<a href="{order[i - 1]}.html">← {E(tps[i - 1]["title"])}</a>' if i else "<span></span>"
        nxt = f'<a href="{order[i + 1]}.html">{E(tps[i + 1]["title"])} →</a>' if i + 1 < len(order) else "<span></span>"
        rendered = markdown.render(body)
        if t.get("summary"):
            rendered = rendered.replace("</h1>", f"</h1><p class=summary>{E(t['summary'])}</p>", 1)
        out[f"docs/{t['topic']}.html"] = _page(t["title"], rendered + f'<nav class="pager" aria-label="Pages">{prev}{nxt}</nav>', current=t["topic"], root="", tps=tps)
        for s in docs._pages()[t["topic"]]["sections"]:
            search.append({"u": f"{t['topic']}.html" + (f"#{s['id']}" if s["id"] else ""), "t": s["title"] or t["title"], "p": t["title"],
                           "w": re.sub(r"\s+", " ", (s["title"] + " " + s["text"]).lower())[:4000]})
    # index
    cards = "".join(f'<a class="card" href="{t["topic"]}.html"><b>{E(t["title"])}</b><span>{E(t["summary"])}</span></a>' for t in tps)
    intro = markdown.render("""# Jade Agent Stack

One Python package to drive the Jade repositories: **Vault** (control plane), **Agent Base** (resource plane),
**Agent Kit** (the embeddable subset of Vault) and **Agent UI/UX** (presentation). It is a client, not a fork, and it
needs the network to reach them.

```sh
pip install jade-agent-stack
jade init && jade doctor
jade site new "Acme AI" --template saas && jade site build && jade site preview
```

People read these pages; agents read [the Markdown](md/) and [llms.txt](llms.txt), or ask `jade docs search`.""")
    out["docs/index.html"] = _page("Documentation", intro + f'<h2>Topics</h2><div class="cards">{cards}</div>', current="index", root="", tps=tps)
    out["docs/search.json"] = json.dumps(search, separators=(",", ":"))
    out["docs/md/index.md"] = "# Jade Agent Stack docs (Markdown)\n\n" + "\n".join(f"- [{t['title']}]({t['topic']}.md): {t['summary']}" for t in tps) + "\n\n" + FOOT_MD.format(src="") + "\n"
    llms = llms_txt(tps, base=PAGES + "/md/")
    out["docs/llms.txt"] = llms
    out["llms.txt"] = llms
    out["docs/catalog.json"] = json.dumps(catalog(tps), indent=1) + "\n"
    out["AGENTS.md"] = agents_md(tps)
    out["STACK.md"] = stack_md()
    out["schema/playbook.v1.json"] = json.dumps(__import__("jade.playbook.engine", fromlist=["SCHEMA"]).SCHEMA, indent=2) + "\n"
    out["docs/.nojekyll"] = ""
    out["docs/examples/index.html"] = examples_page(root, tps)
    return out


def llms_txt(tps: list[dict], base: str) -> str:
    lines = ["# Jade Agent Stack", "", "> A Python client, CLI, wizard, harness, playbook runner and site compiler for Jade Vault, Jade Agent Base, Jade Agent Kit and Jade Agent UI/UX.", "",
             f"Version {compat.TOOLKIT}. Install: `pip install jade-agent-stack`. Every command: `jade commands --json`. Search: `jade docs search <words>`.", "", "## Docs", ""]
    lines += [f"- [{t['title']}]({base}{t['topic']}.md): {t['summary']}" for t in tps]
    lines += ["", "## Reference", "", "- Config: `jade.config.yaml` (upward from cwd, or $JADE_CONFIG); secrets in the OS keyring as `jade.<host>`.",
              "- Output: `--json` gives {\"schema\": \"jade.v1\", \"ok\": bool, \"data\" | \"error\": {code, message, remediation}}.",
              "- Exit codes: 0 ok, 1 user error, 2 remote error, 3 refused for safety.",
              "- Site spec: `jade.site.yaml`; templates: " + ", ".join(__import__("jade.site.spec", fromlist=["templates"]).templates()) + ".",
              "- Playbooks: `*.playbook.yaml`, apiVersion jade/v1, schema/playbook.v1.json.", ""]
    return "\n".join(lines)


