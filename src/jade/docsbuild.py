def examples_page(root: Path, tps: list[dict]) -> str:
    ex = Path(root) / "examples" / "sites"
    items = []
    for d in sorted(ex.iterdir()) if ex.exists() else []:
        spec = d / "jade.site.yaml"
        if not spec.exists():
            continue
        import yaml
        s = yaml.safe_load(spec.read_text()) or {}
        items.append(f'<a class="card" href="{E(d.name)}/"><b>{E(s.get("name", d.name))}</b><span>{E(s.get("tagline", ""))} '
                     f'(template {E(s.get("template", "none"))}, theme {E(s.get("theme", "jade") if isinstance(s.get("theme", "jade"), str) else s["theme"].get("name"))})</span></a>')
    pbs = sorted((Path(root) / "examples").glob("*.playbook.yaml"))
    pb_list = "".join(f'<li><a href="{REPO}/blob/main/examples/{p.name}"><code>{E(p.name)}</code></a></li>' for p in pbs)
    body = markdown.render("# Examples\n\nEach site below is built by `jade site build` from a few lines of `jade.site.yaml` "
                           "(in `examples/sites/<name>/`). Sites that need a backend show their pages, and their forms and sign-in work once deployed to a Jade Agent Base.")
    body += f'<div class="cards">{"".join(items)}</div><h2>Playbooks</h2><ul>{pb_list}</ul>'
    return _page("Examples", body, current="examples", root="../", tps=tps)


def build(out: Path | None = None, *, format: str = "both", check: bool = False, root: Path | None = None, sites: bool = True) -> dict:
    """write (or with check, compare) every generated file; also builds the example sites into docs/examples/"""
    root = Path(root or Path.cwd())
    files = outputs(root)
    if format == "md":
        files = {k: v for k, v in files.items() if not k.endswith(".html") and k != "docs/search.json"}
    elif format == "html":
        files = {k: v for k, v in files.items() if not k.startswith("docs/md/")}
    if out and Path(out).name != "docs":
        files = {(str(Path(out) / k[5:]) if k.startswith("docs/") else k): v for k, v in files.items()}
    if sites:
        for k, v in example_sites(root).items():
            files[k] = v
    stale = []
    for rel, text in files.items():
        p = root / rel
        if check:
            if not p.exists() or p.read_text() != text:
                stale.append(rel)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            if not p.exists() or p.read_text() != text:
                p.write_text(text)
    if check and stale:
        raise JadeError(f"{len(stale)} generated file(s) are stale: {', '.join(stale[:8])}{' …' if len(stale) > 8 else ''}. ", "JADE406", data={"stale": stale})
    return {"files": len(files), "checked" if check else "written": len(files), "stale": stale}


def example_sites(root: Path) -> dict[str, str]:
    from .site.compiler import compile_site
    from .site.spec import Site, validate
    out = {}
    ex = root / "examples" / "sites"
    for d in sorted(ex.iterdir()) if ex.exists() else []:
        if not (d / "jade.site.yaml").exists():
            continue
        s = Site.load(d)
        e = s.expanded()
        validate(e, s.dir)
        for rel, text in compile_site(e, base_dir=s.dir)["files"].items():
            out[f"docs/examples/{d.name}/{rel}"] = text
    return out


def report(root: Path) -> list[str]:
    """warnings: dead links, undocumented commands"""
    warn = []
    files = outputs(root)
    names = {k[5:] for k in files if k.startswith("docs/")}
    for k, v in files.items():
        if not k.endswith(".html") or "/examples/" in k:
            continue
        for href in re.findall(r'href="([^"#:]+\.html)(?:#[^"]*)?"', v):
            if href not in names and not href.startswith("../"):
                warn.append(f"{k}: dead link {href}")
    for c in commands.REGISTRY.values():
        if not c.help:
            warn.append(f"command {c.name} has no help")
        for p in c.params:
            if not p.help and not p.positional and p.name not in ("timeout", "model", "session", "tool", "title"):
                warn.append(f"command {c.name}: --{p.name} has no help")
    return warn
